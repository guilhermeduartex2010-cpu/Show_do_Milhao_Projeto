
create extension if not exists pgcrypto;

create table if not exists public.jogos (
  id uuid primary key default gen_random_uuid(),
  nome text not null unique
);

create table if not exists public.perguntas (
  id bigint generated by default as identity primary key,
  enunciado text not null,
  alternativa_a text not null,
  alternativa_b text not null,
  alternativa_c text not null,
  alternativa_d text not null,
  correta char(1) not null check (lower(correta) in ('a','b','c','d')),
  dificuldade text not null check (dificuldade in ('facil','media','dificil'))
);

create table if not exists public.partidas (
  id uuid primary key,
  jogo_id uuid not null references public.jogos(id),
  apelido text not null check (length(trim(apelido)) > 0),
  valor_ganho numeric(12,2) not null default 0,
  tempo_segundos numeric(10,2) not null,
  acertos integer not null check (acertos between 0 and 9),
  motivo_encerramento text not null,
  data_hora timestamptz not null default now()
);

alter table public.jogos enable row level security;
alter table public.perguntas enable row level security;
alter table public.partidas enable row level security;

-- Políticas didáticas: a chave anon permite leitura pública das tabelas necessárias.
-- Em produção, restrinja inserções/leituras e valide pontuação no servidor.
create policy "leitura jogos" on public.jogos for select to anon using (true);
create policy "leitura perguntas" on public.perguntas for select to anon using (true);
create policy "leitura partidas" on public.partidas for select to anon using (true);
create policy "inserir partidas" on public.partidas for insert to anon with check (true);
create policy "criar jogo" on public.jogos for insert to anon with check (true);

